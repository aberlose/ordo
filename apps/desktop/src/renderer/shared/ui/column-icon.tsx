export { COLUMN_ICON_NAMES };

export function ColumnIcon({ icon, ...props }: { icon: string | null } & Omit<LucideProps, 'name'>) {
  const Icon = isColumnIconName(icon) ? COLUMN_ICONS[icon] : CircleDashed;
  return <Icon aria-hidden {...props} />;
}

/** Lower case without accents, for accent-insensitive search. */
export const foldText = (text: string): string =>
  text
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae');
